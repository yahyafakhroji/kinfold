import { afterEach, expect, test } from 'bun:test'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, sep } from 'node:path'
import { COMPILED_SNAPSHOT_WORKER_PATH } from '../src/backup/snapshot'
import { COMPILED_WORKER_PATH } from '../src/vectors/vector-worker'
import { type BuildToolchain, type Host, type ReleasePaths, buildRelease, programName, releasePaths } from './build-release'
import { posixOnly } from '../test/platform-guards'

const REPO = join(import.meta.dir, '..')
/** The committed stubs, so a restore is compared with what the repository holds. */
const VERSION_STUB = readFileSync(join(REPO, 'src', 'version.ts'))
const GENERATED_STUB = readFileSync(join(REPO, 'src', 'runtime', 'embedded.generated.ts'))
const GENERATED_LEFTOVER = "// Generated by tools/gen-embedded.ts for linux-x64; a release build only. Do not commit.\nexport const embedded: GeneratedAssets = {}\n"
const VERSION_LEFTOVER = "// Stamped by tools/build-release.ts; do not commit.\nexport const VERSION = '0.2.0'\n"
const LINUX_X64: Host = { platform: 'linux', arch: 'x64' }

let root: string | null = null

afterEach(() => {
  if (root !== null) rmSync(root, { recursive: true, force: true })
  root = null
})

function workspace(): ReleasePaths {
  root = mkdtempSync(join(tmpdir(), 'kinfold-build-release-'))
  mkdirSync(join(root, 'src', 'runtime'), { recursive: true })
  mkdirSync(join(root, 'tools'), { recursive: true })
  writeFileSync(join(root, 'src', 'version.ts'), VERSION_STUB)
  writeFileSync(join(root, 'src', 'runtime', 'embedded.generated.ts'), GENERATED_STUB)
  return releasePaths(root)
}

function toolchain(overrides: Partial<BuildToolchain> = {}): BuildToolchain {
  return {
    generate(paths) {
      writeFileSync(paths.generated, GENERATED_LEFTOVER)
    },
    compile(paths, _bunTarget, output) {
      writeFileSync(output, 'kinfold program\n', { mode: 0o755 })
      return 0
    },
    ...overrides,
  }
}

test('a failed compile restores both committed stubs byte for byte', async () => {
  const paths = workspace()
  const build = buildRelease(paths, 'linux-x64', '0.2.0', toolchain({ compile: () => 1 }), LINUX_X64)

  await expect(build).rejects.toThrow('compile exited 1')
  expect(readFileSync(paths.versionFile).equals(VERSION_STUB)).toBe(true)
  expect(readFileSync(paths.generated).equals(GENERATED_STUB)).toBe(true)
})

posixOnly('POSIX paths')('a stamped version file makes the build refuse before it writes anything', async () => {
  const paths = workspace()
  writeFileSync(paths.versionFile, VERSION_LEFTOVER)
  let generated = 0
  const build = buildRelease(
    paths,
    'linux-x64',
    '0.2.0',
    toolchain({
      generate() {
        generated += 1
      },
    }),
    LINUX_X64,
  )

  await expect(build).rejects.toThrow('src/version.ts is not the committed stub')
  expect(generated).toBe(0)
  expect(readFileSync(paths.versionFile, 'utf8')).toBe(VERSION_LEFTOVER)
})

posixOnly('POSIX paths')('a generated asset file makes the build refuse before it writes anything', async () => {
  const paths = workspace()
  writeFileSync(paths.generated, GENERATED_LEFTOVER)
  let compiled = 0
  const build = buildRelease(
    paths,
    'linux-x64',
    '0.2.0',
    toolchain({
      compile() {
        compiled += 1
        return 0
      },
    }),
    LINUX_X64,
  )

  await expect(build).rejects.toThrow('src/runtime/embedded.generated.ts is not the committed stub')
  expect(compiled).toBe(0)
  expect(readFileSync(paths.generated, 'utf8')).toBe(GENERATED_LEFTOVER)
})

test('a target on another host is refused with the host and target named', async () => {
  const paths = workspace()
  const build = buildRelease(paths, 'linux-x64', '0.2.0', toolchain(), { platform: 'darwin', arch: 'arm64' })

  await expect(build).rejects.toThrow('linux-x64 needs linux x64; this host is darwin arm64')
})

test('a successful build restores the stubs and reports the program', async () => {
  const paths = workspace()
  const summary = await buildRelease(paths, 'linux-x64', '0.2.0', toolchain(), LINUX_X64)

  expect(summary.program).toBe('kinfold-linux-x64')
  expect(summary.size).toBe('kinfold program\n'.length)
  expect(summary.sha256).toMatch(/^[0-9a-f]{64}$/)
  expect(readFileSync(paths.versionFile).equals(VERSION_STUB)).toBe(true)
  expect(readFileSync(paths.generated).equals(GENERATED_STUB)).toBe(true)
})

test('an unknown target or a non-version is refused', async () => {
  const paths = workspace()

  await expect(buildRelease(paths, 'linux-riscv64', '0.2.0', toolchain(), LINUX_X64)).rejects.toThrow('unknown target linux-riscv64')
  await expect(buildRelease(paths, 'linux-x64', 'not a version', toolchain(), LINUX_X64)).rejects.toThrow('is not a version')
  await expect(buildRelease(paths, 'linux-x64', '0.0.0-dev', toolchain(), LINUX_X64)).rejects.toThrow('development version')
})

test('the compile names each worker as an entry, and every named worker file exists', () => {
  const paths = releasePaths(join(import.meta.dir, '..'))
  expect(paths.workers.map((path) => path.slice(paths.root.length + 1).replaceAll('\\', '/'))).toEqual(['src/vectors/search-worker.ts', 'src/backup/snapshot-worker.ts'])
  for (const worker of paths.workers) expect(existsSync(worker)).toBe(true)
  // The compiled program finds its worker by its path from the entries' common folder.
  const common = join(paths.root, 'src')
  expect([paths.entry, ...paths.workers].every((path) => path.startsWith(`${common}${sep}`))).toBe(true)
  const compiled = paths.workers.map((path) => `./${path.slice(common.length + 1).replaceAll('\\', '/')}`)
  expect(compiled).toEqual([COMPILED_WORKER_PATH, COMPILED_SNAPSHOT_WORKER_PATH])
})

test('the Windows program carries the .exe suffix', () => {
  expect(programName('windows-x64')).toBe('kinfold-windows-x64.exe')
  expect(programName('linux-arm64')).toBe('kinfold-linux-arm64')
})
