// Builds one release program: `bun tools/build-release.ts <target> <version>`.
//
// The embedded asset module and the version module are written for this
// target, compiled into the program, then restored to their committed stubs,
// so a release build leaves the working tree as it found it. The assets come
// from .cache, so the caller builds sqlite3mc for the target and downloads its
// pinned sqlite-vec member first.

import { createHash } from 'node:crypto'
import { createReadStream, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { DEVELOPMENT_VERSION } from '../src/install/self-install'

export interface ReleasePaths {
  root: string
  entry: string
  generator: string
  generated: string
  versionFile: string
  dist: string
}

export interface Host {
  platform: NodeJS.Platform
  arch: string
}

export interface BuildToolchain {
  /** Writes the target's embedded asset module, or throws when it cannot. */
  generate(paths: ReleasePaths, target: string): void
  /** Compiles the entry into the output and returns the exit code. */
  compile(paths: ReleasePaths, bunTarget: string, output: string): number
}

export interface BuildSummary {
  program: string
  path: string
  size: number
  sha256: string
}

interface Target extends Host {
  bun: string
}

/** Bun's compile target for each release target, beside the host that can build it. */
const TARGETS: Readonly<Record<string, Target>> = {
  'darwin-arm64': { bun: 'bun-darwin-arm64', platform: 'darwin', arch: 'arm64' },
  'darwin-x64': { bun: 'bun-darwin-x64', platform: 'darwin', arch: 'x64' },
  'linux-x64': { bun: 'bun-linux-x64', platform: 'linux', arch: 'x64' },
  'linux-arm64': { bun: 'bun-linux-arm64', platform: 'linux', arch: 'arm64' },
  'windows-x64': { bun: 'bun-windows-x64', platform: 'win32', arch: 'x64' },
}

/** The version is written into a string literal, so it holds version characters only. */
const VERSION_PATTERN = /^[0-9A-Za-z][0-9A-Za-z.+-]*$/
const STAMP_HEADER = 'Stamped by tools/build-release.ts'
const GENERATED_HEADER = 'Generated by tools/gen-embedded.ts'
const VERSION_STUB_MARKER = "export const VERSION = '0.0.0-dev'"
const GENERATED_STUB_MARKER = 'export const embedded: GeneratedAssets | null = null'

export class BuildError extends Error {
  override name = 'BuildError'
}

export function releasePaths(root: string): ReleasePaths {
  return {
    root,
    entry: join(root, 'src', 'cli', 'kinfold.ts'),
    generator: join(root, 'tools', 'gen-embedded.ts'),
    generated: join(root, 'src', 'runtime', 'embedded.generated.ts'),
    versionFile: join(root, 'src', 'version.ts'),
    dist: join(root, 'dist'),
  }
}

export function programName(target: string): string {
  return `kinfold-${target}${target === 'windows-x64' ? '.exe' : ''}`
}

/**
 * A file stamped or generated by an earlier build is not a stub. The next
 * build would adopt it as one, so the build refuses to start instead.
 */
function assertCommittedStub(paths: ReleasePaths, file: string, bytes: Buffer, marker: string, header: string): void {
  const text = bytes.toString('utf8')
  if (text.includes(marker) && !text.includes(header)) return
  const shown = relative(paths.root, file)
  throw new BuildError(`${shown} is not the committed stub; a failed or interrupted build left it written, so restore it with git checkout -- ${shown}`)
}

async function sha256(path: string): Promise<string> {
  const hash = createHash('sha256')
  for await (const chunk of createReadStream(path)) hash.update(chunk)
  return hash.digest('hex')
}

export async function buildRelease(
  paths: ReleasePaths,
  targetName: string,
  version: string,
  toolchain: BuildToolchain,
  host: Host = { platform: process.platform, arch: process.arch },
): Promise<BuildSummary> {
  if (targetName === '' || version === '') throw new BuildError('usage: bun tools/build-release.ts <target> <version>')
  const target = TARGETS[targetName]
  if (target === undefined) throw new BuildError(`unknown target ${targetName}; expected one of ${Object.keys(TARGETS).join(', ')}`)
  if (!VERSION_PATTERN.test(version)) throw new BuildError(`${version} is not a version; use letters, digits, dots, plus and hyphen`)
  // The program skips its checksum check for this version, so a release must never carry it.
  if (version === DEVELOPMENT_VERSION) throw new BuildError(`${version} is the development version, which skips the checksum check; build a real release version`)
  if (host.platform !== target.platform || host.arch !== target.arch) {
    throw new BuildError(`${targetName} needs ${target.platform} ${target.arch}; this host is ${host.platform} ${host.arch}, and the build embeds a sqlite3mc library compiled for the target`)
  }

  // Read the stubs before any write, so the restore is exact even when the
  // build fails halfway through.
  const versionStub = readFileSync(paths.versionFile)
  const assetsStub = readFileSync(paths.generated)
  assertCommittedStub(paths, paths.versionFile, versionStub, VERSION_STUB_MARKER, STAMP_HEADER)
  assertCommittedStub(paths, paths.generated, assetsStub, GENERATED_STUB_MARKER, GENERATED_HEADER)

  let restored = false
  const restore = (): void => {
    if (restored) return
    restored = true
    writeFileSync(paths.versionFile, versionStub)
    writeFileSync(paths.generated, assetsStub)
  }
  // A signal must not leave the stamped files behind. The handler restores
  // before exiting because process.exit does not unwind to the finally.
  const onInterrupt = (): void => {
    restore()
    process.exit(130)
  }
  const onTerminate = (): void => {
    restore()
    process.exit(143)
  }
  process.on('SIGINT', onInterrupt)
  process.on('SIGTERM', onTerminate)

  try {
    toolchain.generate(paths, targetName)
    // Bun's define replaces a global reference, not an imported binding, so the
    // version module is stamped for the compile and restored afterwards.
    writeFileSync(paths.versionFile, `// ${STAMP_HEADER}; do not commit.\nexport const VERSION = '${version}'\n`, { mode: 0o644 })
    mkdirSync(paths.dist, { recursive: true, mode: 0o755 })
    const program = programName(targetName)
    const output = join(paths.dist, program)
    const exitCode = toolchain.compile(paths, target.bun, output)
    if (exitCode !== 0) throw new BuildError(`compile exited ${exitCode}`)
    const { size } = statSync(output)
    return { program, path: output, size, sha256: await sha256(output) }
  } finally {
    process.off('SIGINT', onInterrupt)
    process.off('SIGTERM', onTerminate)
    restore()
  }
}

const nativeToolchain: BuildToolchain = {
  generate(paths, target) {
    const result = Bun.spawnSync([process.execPath, paths.generator, target], { cwd: paths.root, stdout: 'inherit', stderr: 'inherit' })
    if (result.exitCode !== 0) throw new BuildError(`asset generation exited ${result.exitCode ?? 'without a code'}`)
  },
  compile(paths, bunTarget, output) {
    const result = Bun.spawnSync(
      [process.execPath, 'build', '--compile', `--target=${bunTarget}`, paths.entry, '--outfile', output],
      { cwd: paths.root, stdout: 'inherit', stderr: 'inherit' },
    )
    return result.exitCode ?? 1
  },
}

async function main(): Promise<void> {
  const paths = releasePaths(join(import.meta.dir, '..'))
  const summary = await buildRelease(paths, process.argv[2] ?? '', process.argv[3] ?? '', nativeToolchain)
  console.log(`built ${relative(paths.root, summary.path)} size=${summary.size} sha256=${summary.sha256}`)
}

if (import.meta.main) {
  try {
    await main()
  } catch (error) {
    if (!(error instanceof BuildError)) throw error
    console.error(`build failed: ${error.message}`)
    // The restore has already run in the build's finally.
    process.exitCode = 1
  }
}
